/**
 * Support for the Chunk-2 privileged proofs.
 *
 * WHY IT BUILDS A REAL ADMINISTRATOR RATHER THAN A FIXTURE. Every property
 * these suites assert depends on the chain being genuine: the one-time
 * bootstrap creates the first assignment, the account enrols a second factor
 * and confirms its recovery codes, and only then does a step-up grant turn
 * into a `PrivilegedActor`. A hand-built actor would let a suite prove that
 * administration works while proving nothing about the conditions it is
 * supposed to be under (SECURITY_BASELINE.md §8).
 *
 * THE TOTP CODES ARE GENERATED BY THE LIBRARY'S OWN IMPLEMENTATION, from the
 * secret in the enrolment URI. A hand-rolled RFC 6238 here would be a second
 * implementation, and a proof that two of this repository's opinions agree
 * rather than that an authenticator app would work.
 */

/** The digits and period the composition root configures. */
const TOTP = { digits: 6, period: 30 } as const;

/**
 * The current code for an enrolment URI.
 *
 * The URI carries the secret base32-encoded, which is the form an authenticator
 * app reads; the library holds the raw value. Decoding is what makes the code
 * this produces the code the app would produce.
 */
export async function codeFor(totpUri: string): Promise<string> {
  const encoded = new URL(totpUri).searchParams.get('secret');
  if (encoded === null) throw new Error('The enrolment URI carries no secret.');

  const secret = new TextDecoder().decode(base32.decode(encoded));
  return createOTP(secret, TOTP).totp();
}

export interface ProofAccount {
  readonly accountId: string;
  readonly email: string;
  /** A `Cookie` header carrying this account's current session. */
  cookie: string;
  readonly sessionId: string;
}

/**
 * Creates a verified, signed-in account through the REAL flows.
 *
 * Sign-up, the emailed verification link, and a credential sign-in — the same
 * path a person takes, because an account inserted directly would skip exactly
 * the state these suites then reason about.
 */
export async function createAccount(
  harness: IdentityHarness,
  provider: CapturingProvider,
  prefix = 'authz',
): Promise<ProofAccount> {
  const email = freshEmail(prefix);

  await harness.identity.signUp(anonymousContext(), {
    email,
    password: PROOF_PASSWORD,
    name: 'Authorisation Proof',
  });
  await harness.dispatch();

  const link = provider.lastLinkTo(email);
  if (link === null) throw new Error(`No verification link for ${email}`);

  const { token } = linkParameters(link);
  await harness.identity.confirmVerification(anonymousContext(), { email, token });

  return signIn(harness, email);
}

/** Signs an account in and returns its cookie and session id. */
export async function signIn(
  harness: IdentityHarness,
  email: string,
  password = PROOF_PASSWORD,
): Promise<ProofAccount> {
  const outcome = await harness.identity.signIn(anonymousContext(), { email, password });
  if (!outcome.ok) throw new Error(`Sign-in failed for ${email}: ${outcome.failure}`);
  if (outcome.state !== 'authenticated') {
    throw new Error(`Sign-in for ${email} was challenged; use signInWithFactor.`);
  }

  const cookie = cookieHeader(outcome.setCookies);
  const session = await harness.session.resolve(new Headers({ cookie }));
  if (session.state !== 'active') throw new Error('The new session is not active.');

  return {
    accountId: outcome.account.id,
    email,
    cookie,
    sessionId: session.session.sessionId,
  };
}

/**
 * Signs in an account that HAS a second factor, answering the challenge.
 *
 * A correct password no longer produces a session for such an account: the
 * library issues a short-lived challenge instead. A helper that ignored that
 * would only work for accounts the privileged proofs are not about.
 */
export async function signInWithFactor(
  harness: IdentityHarness,
  account: Administrator,
): Promise<ProofAccount> {
  const challenged = await harness.identity.signIn(anonymousContext(), {
    email: account.email,
    password: PROOF_PASSWORD,
  });
  if (!challenged.ok) throw new Error(`Sign-in failed: ${challenged.failure}`);
  if (challenged.state !== 'second-factor-required') {
    throw new Error('Expected a second-factor challenge.');
  }

  const completed = await harness.identity.completeSecondFactor(
    sessionContext(cookieHeader(challenged.setCookies)),
    { code: await codeFor(account.totpUri), kind: 'totp' },
  );
  if (!completed.ok) throw new Error(`Challenge failed: ${completed.failure}`);

  const cookie = cookieHeader(completed.setCookies);
  const session = await harness.session.resolve(new Headers({ cookie }));
  if (session.state !== 'active') throw new Error('The new session is not active.');

  return {
    accountId: completed.account.id,
    email: account.email,
    cookie,
    sessionId: session.session.sessionId,
  };
}

/** Resolves the live session an account's cookie names. */
export async function sessionOf(harness: IdentityHarness, account: ProofAccount) {
  const outcome = await harness.session.resolve(new Headers({ cookie: account.cookie }));
  if (outcome.state !== 'active') {
    throw new Error(`Session for ${account.email} is ${outcome.reason}.`);
  }
  return outcome.session;
}

/**
 * Enrols a second factor and confirms the recovery codes.
 *
 * BOTH HALVES, because the posture is not complete without both — an enrolled
 * factor whose recovery codes were never confirmed is exactly the incomplete
 * state the authorisation service refuses (§8.2).
 *
 * The session is REPLACED when the factor is verified, so the account's cookie
 * is updated here rather than by each caller remembering to.
 */
export async function enrolSecondFactor(
  harness: IdentityHarness,
  account: ProofAccount,
): Promise<{
  totpUri: string;
  recoveryCodes: readonly string[];
  recoveryCodeReceipt: string;
}> {
  const context = sessionContext(account.cookie);
  const session = await sessionOf(harness, account);

  const started = await harness.privilegedSecurity.beginEnrolment(context, session, {
    password: PROOF_PASSWORD,
  });
  if (!started.ok) throw new Error(`Enrolment refused: ${started.failure}`);

  const confirmed = await harness.privilegedSecurity.confirmEnrolment(
    sessionContext(account.cookie),
    session,
    { code: await codeFor(started.totpUri) },
  );
  if (!confirmed.ok) throw new Error(`Verification refused: ${confirmed.failure}`);

  const rotated = cookieHeader(confirmed.setCookies);
  if (rotated !== '') Object.assign(account, { cookie: rotated });

  const acknowledged = await harness.privilegedSecurity.confirmRecoveryCodes(
    await sessionOf(harness, account),
    { issuanceReceipt: started.recoveryCodeReceipt },
  );
  if (!acknowledged.ok) throw new Error(`Codes refused: ${acknowledged.failure}`);

  return {
    totpUri: started.totpUri,
    recoveryCodes: started.recoveryCodes,
    recoveryCodeReceipt: started.recoveryCodeReceipt,
  };
}

/**
 * Runs the one-time bootstrap the way the host-only command does.
 *
 * Through the SAME stored procedure, with the migration session standing in for
 * the operator principal: `db:test:operator` proves that the operator principal
 * is the one that may execute it and the application principal is not, and this
 * proves what the procedure DOES.
 */
export async function bootstrapAdministrator(
  admin: SqlSession,
  accountId: string,
  ticket = 'PROOF-1 first administrator',
): Promise<void> {
  await admin.execute('IdentityBootstrapPlatformAdministrator', {
    targetUserId: accountId,
    ticket,
  });
}

/**
 * A complete privileged administrator: bootstrapped, enrolled, stepped up.
 *
 * Returns the actor and the material a test needs to keep acting as them.
 */
export interface Administrator extends ProofAccount {
  readonly totpUri: string;
  readonly recoveryCodes: readonly string[];
}

export async function createAdministrator(
  harness: IdentityHarness,
  provider: CapturingProvider,
  admin: SqlSession,
  prefix = 'admin',
): Promise<Administrator> {
  const account = await createAccount(harness, provider, prefix);
  await bootstrapAdministrator(admin, account.accountId);

  const enrolment = await enrolSecondFactor(harness, account);

  return { ...account, ...enrolment, cookie: account.cookie };
}

/**
 * Earns a step-up grant and turns it into a `PrivilegedActor`.
 *
 * Through `requirePrivilegedAction`, which is the only producer of one — so a
 * suite cannot accidentally act with an authority the runtime would refuse.
 */
export async function actorFor(
  harness: IdentityHarness,
  account: Administrator,
  permission: Parameters<
    typeof harness.authorization.requirePrivilegedAction
  >[0]['permission'],
  purpose:
    | 'privilege-administration'
    | 'account-administration'
    | 'second-factor'
    | 'quran-canonical-edit'
    | 'hadith-canonical-edit',
): Promise<PrivilegedActor> {
  const session = await sessionOf(harness, account);

  // REUSES A LIVE GRANT, which is what a person does: they prove themselves
  // once and make several changes inside the short window. Earning a fresh
  // grant per action would also spend the step-up and signed-in TOTP budgets
  // five times over — the limiter working exactly as intended, and a suite
  // failing for a reason unrelated to what it tests.
  let decision = await harness.authorization.requirePrivilegedAction({
    session,
    permission,
    stepUp: purpose,
  });

  if (decision.state === 'denied' && decision.reason === 'step-up-required') {
    const granted = await harness.privilegedSecurity.beginStepUp(
      sessionContext(account.cookie),
      session,
      {
        purpose,
        password: PROOF_PASSWORD,
        code: await codeFor(account.totpUri),
      },
    );
    if (!granted.ok) throw new Error(`Step-up refused: ${granted.failure}`);

    decision = await harness.authorization.requirePrivilegedAction({
      session,
      permission,
      stepUp: purpose,
    });
  }

  if (decision.state !== 'allowed') {
    throw new Error(`Privileged action refused: ${decision.reason}`);
  }

  return decision.actor;
}

/** How many live sessions an account holds, read straight from the table. */
export async function sessionCount(
  admin: SqlSession,
  accountId: string,
): Promise<number> {
  const [row] = await admin.query<{ total: number }>(
    `SELECT COUNT_BIG(*) AS total FROM [dbo].[Session] WHERE [userId] = N'${accountId}';`,
  );
  return Number(row?.total ?? 0);
}

/** How many live step-up grants an account holds. */
export async function grantCount(admin: SqlSession, accountId: string): Promise<number> {
  const [row] = await admin.query<{ total: number }>(
    `SELECT COUNT_BIG(*) AS total FROM [dbo].[StepUpGrant] WHERE [userId] = N'${accountId}';`,
  );
  return Number(row?.total ?? 0);
}
