/**
 * The Quran adapter's WORD-BY-WORD works (Quran Part 7; DOMAIN_MODEL.md §8.7).
 *
 * OWNED BY THE QURAN CONTEXT, hosted here, and spread into
 * `createQuranPersistence` so Quran keeps one persistence port. A work is a
 * layered work of a Translation's shape — its own slug, Language, source,
 * lifecycle, version and contributors — whose content is one gloss per word
 * of the Arabic, typed to the Ayah by its citation and to the word by its
 * position. Nothing here derives a word or a gloss: the service has already
 * checked every position against the Ayah's stored text (`ayahWords`).
 *
 * TEXT IS STORED EXACTLY AS GIVEN, and every write is ONE transaction under the
 * work's expected version (`claim`) with its audit entry — counts and field
 * names only, never a word. Glosses are not indexed for search, so no write
 * here owes a search intent.
 */

const WORK_SELECT = {
  id: true,
  slug: true,
  name: true,
  description: true,
  attribution: true,
  languageCode: true,
  sourceId: true,
  state: true,
  version: true,
  createdAt: true,
  updatedAt: true,
  publishedAt: true,
  source: { select: { authority: true } },
  contributors: {
    select: { personId: true, role: true, position: true },
    orderBy: [{ position: 'asc' }, { personId: 'asc' }, { role: 'asc' }],
  },
} satisfies Prisma.QuranWordByWordSelect;

/**
 * A work as `WORK_SELECT` reads it — spelled out, as `./layers.ts` spells its
 * rows, so nothing generated by the client is named outside a query.
 */
interface WorkRow {
  readonly id: string;
  readonly slug: string;
  readonly name: string;
  readonly description: string | null;
  readonly attribution: string | null;
  readonly languageCode: string;
  readonly sourceId: string | null;
  readonly state: string;
  readonly version: number;
  readonly createdAt: Date;
  readonly updatedAt: Date;
  readonly publishedAt: Date | null;
  readonly source: { readonly authority: string } | null;
  readonly contributors: readonly {
    readonly personId: string;
    readonly role: string;
    readonly position: number;
  }[];
}

/** How many ayat each of these works glosses — ONE grouped read. */
async function glossedAyat(
  db: Client,
  ids: readonly string[],
): Promise<ReadonlyMap<string, number>> {
  if (ids.length === 0) return new Map();
  const rows = await db.quranWordByWordGloss.groupBy({
    by: ['wordByWordId', 'surahNumber', 'ayahNumber'],
    where: { wordByWordId: { in: [...ids] } },
  });
  const counted = new Map<string, number>();
  for (const row of rows)
    counted.set(row.wordByWordId, (counted.get(row.wordByWordId) ?? 0) + 1);
  return counted;
}

function toRecord(row: WorkRow, textCount: number): WordByWordRecord {
  return {
    id: row.id,
    slug: row.slug,
    name: row.name,
    description: row.description,
    attribution: row.attribution,
    languageCode: row.languageCode,
    sourceId: row.sourceId,
    sourceAuthority: authorityOf(row.source),
    state: stateOf(row.state),
    version: row.version,
    textCount,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
    publishedAt: row.publishedAt,
    contributors: row.contributors.map((entry) => ({
      personId: entry.personId,
      role: entry.role as QuranContributorRole,
      position: entry.position,
    })),
  };
}

async function recordOf(tx: Client, id: string): Promise<WordByWordRecord> {
  const row = await tx.quranWordByWord.findUnique({ where: { id }, select: WORK_SELECT });
  if (row === null) throw new QuranDataError('conflict');
  return toRecord(row, (await glossedAyat(tx, [id])).get(id) ?? 0);
}

/** A work's own descriptive columns — never its slug, which is set once. */
function workColumns(value: {
  readonly name: string;
  readonly description: string | null;
  readonly attribution: string | null;
  readonly languageCode: string;
  readonly sourceId: string | null;
}) {
  return {
    name: value.name,
    description: value.description,
    attribution: value.attribution,
    languageCode: value.languageCode,
    sourceId: value.sourceId,
  };
}

async function replaceContributors(
  tx: Client,
  id: string,
  contributors: readonly { readonly personId: string; readonly role: string }[],
): Promise<void> {
  await tx.quranWordByWordContributor.deleteMany({ where: { wordByWordId: id } });
  if (contributors.length > 0)
    await tx.quranWordByWordContributor.createMany({
      data: contributors.map((entry, position) => ({
        wordByWordId: id,
        personId: entry.personId,
        role: entry.role,
        position,
      })),
    });
}

/**
 * One Surah's changed ayat, each Ayah's glosses replaced WHOLE, in three
 * set-based statements over one bound JSON document read with `OPENJSON`:
 * replace the glosses that exist, insert the ones that do not, then remove
 * the changed ayat's glosses the document no longer names. Removal comes
 * LAST, so a published work is never seen without a gloss in between (its
 * trigger refuses only the state the save ends in). Every character arrives
 * exactly as supplied.
 */
async function writeGlosses(
  tx: Client,
  workId: string,
  surah: number,
  changes: readonly WordGlossChange[],
): Promise<{ readonly saved: number; readonly removed: number }> {
  const rows = changes.flatMap((change) =>
    change.glosses.map((gloss) => ({
      ayah: change.ayah,
      position: gloss.position,
      text: gloss.text,
    })),
  );
  const ayat = JSON.stringify(changes.map((change) => change.ayah));
  if (rows.length > 0) {
    const document = JSON.stringify(rows);
    await tx.$executeRaw`UPDATE g SET g.[text] = j.[text]
      FROM [dbo].[QuranWordByWordGloss] g
      JOIN OPENJSON(${document}) WITH ([ayah] INT '$.ayah', [position] INT '$.position', [text] NVARCHAR(200) '$.text') j
        ON j.[ayah] = g.[ayahNumber] AND j.[position] = g.[position]
      WHERE g.[wordByWordId] = ${workId} AND g.[surahNumber] = ${surah}`;
    await tx.$executeRaw`INSERT INTO [dbo].[QuranWordByWordGloss] ([wordByWordId], [surahNumber], [ayahNumber], [position], [text])
      SELECT ${workId}, ${surah}, j.[ayah], j.[position], j.[text]
      FROM OPENJSON(${document}) WITH ([ayah] INT '$.ayah', [position] INT '$.position', [text] NVARCHAR(200) '$.text') j
      WHERE NOT EXISTS (
        SELECT 1 FROM [dbo].[QuranWordByWordGloss] g
        WHERE g.[wordByWordId] = ${workId} AND g.[surahNumber] = ${surah}
          AND g.[ayahNumber] = j.[ayah] AND g.[position] = j.[position]
      )`;
  }
  const kept = JSON.stringify(
    rows.map((row) => ({ ayah: row.ayah, position: row.position })),
  );
  const removed = await tx.$executeRaw`DELETE g FROM [dbo].[QuranWordByWordGloss] g
    WHERE g.[wordByWordId] = ${workId} AND g.[surahNumber] = ${surah}
      AND g.[ayahNumber] IN (SELECT CAST([value] AS INT) FROM OPENJSON(${ayat}))
      AND NOT EXISTS (
        SELECT 1 FROM OPENJSON(${kept}) WITH ([ayah] INT '$.ayah', [position] INT '$.position') k
        WHERE k.[ayah] = g.[ayahNumber] AND k.[position] = g.[position]
      )`;
  return { saved: rows.length, removed };
}

type WordByWordPersistence = Pick<
  QuranPersistencePort,
  | 'wordByWords'
  | 'wordByWord'
  | 'createWordByWord'
  | 'updateWordByWord'
  | 'setWordByWordState'
  | 'wordByWordGlosses'
  | 'saveWordByWordGlosses'
>;

export function wordByWordPersistence(): WordByWordPersistence {
  const db = getDatabaseClient();

  return {
    async wordByWords(offset) {
      const [total, rows] = await Promise.all([
        db.quranWordByWord.count(),
        db.quranWordByWord.findMany({
          select: WORK_SELECT,
          orderBy: [...BY_SLUG],
          skip: boundedOffset(offset),
          take: QURAN_PAGE,
        }),
      ]);
      const counted = await glossedAyat(
        db,
        rows.map((row) => row.id),
      );
      return {
        items: rows.map((row) => toRecord(row, counted.get(row.id) ?? 0)),
        total,
        offset: boundedOffset(offset),
      };
    },

    async wordByWord(id) {
      const row = await db.quranWordByWord.findUnique({
        where: { id },
        select: WORK_SELECT,
      });
      return row === null
        ? null
        : toRecord(row, (await glossedAyat(db, [id])).get(id) ?? 0);
    },

    async createWordByWord({ actorId, value }) {
      try {
        return await db.$transaction(async (tx) => {
          const id = randomUUID();
          await tx.quranWordByWord.create({
            data: {
              id,
              slug: value.slug,
              ...workColumns(value),
              state: 'draft',
              version: 1,
              updatedAt: new Date(),
            },
          });
          await replaceContributors(tx, id, value.contributors);
          await audit(tx, {
            actorId,
            action: 'quran.word-by-word.created',
            targetType: 'quran-word-by-word',
            targetId: id,
            after: {
              version: '1',
              state: 'draft',
              source: value.sourceId ?? 'none',
              contributors: String(value.contributors.length),
            },
          });
          return recordOf(tx, id);
        });
      } catch (error) {
        refuse(error);
      }
    },

    async updateWordByWord({ actorId, id, expectedVersion, value }) {
      try {
        return await db.$transaction(async (tx) => {
          const previous = await tx.quranWordByWord.findUnique({
            where: { id },
            select: {
              slug: true,
              state: true,
              version: true,
              sourceId: true,
              publishedAt: true,
              name: true,
              description: true,
              attribution: true,
              languageCode: true,
            },
          });
          guardEdit(previous, expectedVersion, value);
          const changed = await tx.quranWordByWord.updateMany({
            where: { id, version: expectedVersion },
            data: {
              ...workColumns(value),
              version: { increment: 1 },
              updatedAt: new Date(),
            },
          });
          if (changed.count !== 1) throw new QuranDataError('conflict');
          await replaceContributors(tx, id, value.contributors);
          await audit(tx, {
            actorId,
            action: 'quran.word-by-word.updated',
            targetType: 'quran-word-by-word',
            targetId: id,
            before: { version: String(previous.version), state: previous.state },
            after: {
              version: String(previous.version + 1),
              changed: changedFields(previous, workColumns(value)),
              contributors: String(value.contributors.length),
            },
          });
          return recordOf(tx, id);
        });
      } catch (error) {
        refuse(error);
      }
    },

    async setWordByWordState(input) {
      try {
        return await db.$transaction(async (tx) => {
          const previous = await claim(
            tx,
            'word-by-word',
            input.id,
            input.expectedVersion,
            (head) =>
              publication(
                head,
                input.state,
                () =>
                  tx.quranWordByWordGloss.count({ where: { wordByWordId: input.id } }),
                'text-required',
              ),
          );
          await audit(tx, {
            actorId: input.actorId,
            action: 'quran.word-by-word.state-changed',
            targetType: 'quran-word-by-word',
            targetId: input.id,
            before: { version: String(previous.version), state: previous.state },
            after: { version: String(previous.version + 1), state: input.state },
          });
          return recordOf(tx, input.id);
        });
      } catch (error) {
        refuse(error);
      }
    },

    async wordByWordGlosses(id, surah) {
      const rows = await db.quranWordByWordGloss.findMany({
        where: { wordByWordId: id, surahNumber: surah },
        select: { ayahNumber: true, position: true, text: true },
        orderBy: [{ ayahNumber: 'asc' }, { position: 'asc' }],
        take: QURAN_AYAH_NUMBER_MAX * QURAN_WORD_POSITION_MAX,
      });
      return groupByAyah(rows);
    },

    async saveWordByWordGlosses(input) {
      try {
        return await db.$transaction(async (tx) => {
          const previous = await claim(
            tx,
            'word-by-word',
            input.id,
            input.expectedVersion,
          );
          const written = await writeGlosses(tx, input.id, input.surah, input.changes);
          // Which Surah and how many — never a word of the glosses.
          await audit(tx, {
            actorId: input.actorId,
            action: 'quran.word-by-word.glosses-saved',
            targetType: 'quran-word-by-word',
            targetId: input.id,
            before: { version: String(previous.version) },
            after: {
              version: String(previous.version + 1),
              surah: String(input.surah),
              ayat: String(input.changes.length),
              saved: String(written.saved),
              removed: String(written.removed),
            },
          });
          return recordOf(tx, input.id);
        });
      } catch (error) {
        refuse(error);
      }
    },
  };
}

/** Rows in (ayah, position) order, as each Ayah's glosses in position order. */
export function groupByAyah(
  rows: readonly {
    readonly ayahNumber: number;
    readonly position: number;
    readonly text: string;
  }[],
): { readonly ayah: number; readonly glosses: { position: number; text: string }[] }[] {
  const grouped: { ayah: number; glosses: { position: number; text: string }[] }[] = [];
  for (const row of rows) {
    const last = grouped.at(-1);
    const gloss = { position: row.position, text: row.text };
    if (last?.ayah === row.ayahNumber) last.glosses.push(gloss);
    else grouped.push({ ayah: row.ayahNumber, glosses: [gloss] });
  }
  return grouped;
}
